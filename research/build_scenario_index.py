#!/usr/bin/env python3
"""Generate scenarios/index.md from the scenario files.

An index written by hand goes stale the moment a scenario is added or renumbered, which
is the same failure the rest of this project guards against. This reads the files instead.

Usage:
    python3 research/build_scenario_index.py
"""

from __future__ import annotations

import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
SCEN = ROOT / "scenarios"
OUT = SCEN / "index.md"

FILES = [
    ("easy.md", "easy"),
    ("medium.md", "medium"),
    ("hard.md", "hard"),
    ("adversarial.md", "adversarial"),
    ("regression.md", "regression"),
]

DESC = {
    "easy": "Narrow scope, enough information to reach a cause, short path to verifying it.",
    "medium": "Two or more live hypotheses, or a genuine interaction between components.",
    "hard": "Competing causes, and in some cases deliberately insufficient evidence.",
    "adversarial": "Built to break a specific behaviour. Not incidents.",
    "regression": "Cheap to run, sharp to fail on. Rerun after any skill change.",
}

ID_RE = re.compile(r"\b(EASY|MED|HARD|ADV|REG)-(\d{2,3})\b")


def entries(path: Path) -> list[tuple[str, str]]:
    """Return (id, title) for each scenario heading in a file."""
    out = []
    in_fence = False
    for line in path.read_text(encoding="utf-8").splitlines():
        if re.match(r"^\s*(```|~~~)", line):
            in_fence = not in_fence
            continue
        if in_fence:
            continue
        m = re.match(r"^#{2,4}\s+(.*)$", line)
        if not m:
            continue
        text = m.group(1).strip()
        found = ID_RE.search(text)
        if found:
            out.append((found.group(0), text))
    return out


def main() -> int:
    rows = []
    for fname, kind in FILES:
        p = SCEN / fname
        if not p.is_file():
            print(f"missing {p}", file=sys.stderr)
            continue
        for sid, title in entries(p):
            rows.append((kind, sid, title))

    total = len(rows)
    lines = []
    A = lines.append

    A("# Scenario index")
    A("")
    A("Generated by `python3 research/build_scenario_index.py`. Do not edit by hand.")
    A("")
    A(f"{total} scenarios across five files.")
    A("")
    A("The three graded files carry the full section structure. The adversarial and")
    A("regression files are evaluations rather than incident reports, and are labelled as")
    A("such in their own headers.")
    A("")

    for fname, kind in FILES:
        subset = [r for r in rows if r[0] == kind]
        if not subset:
            continue
        A(f"## {kind} ({len(subset)})")
        A("")
        A(DESC[kind])
        A("")
        A("| ID | Scenario |")
        A("| --- | --- |")
        for _kind, sid, title in subset:
            t = re.sub(r"^[A-Z]+-\d+\.?\s*", "", title)
            A(f"| `{sid}` | {t} |")
        A("")

    A("## Using these")
    A("")
    A("Give the agent the initial ticket and initial evidence only. Hold back the")
    A("diagnostic evidence until after the first response, and the ground truth entirely.")
    A("A scenario that leaks its answer is not testing anything.")
    A("")
    A("Score with `evaluation/rubric.md`, and with the scenario's own rubric table where")
    A("the two differ.")
    A("")

    OUT.write_text("\n".join(lines), encoding="utf-8")
    print(f"wrote {OUT}, {total} scenarios")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())